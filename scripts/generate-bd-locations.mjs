/**
 * Generates the compact checkout hierarchy from bangladesh-geo-data 4.0.9
 * (MIT, https://www.npmjs.com/package/bangladesh-geo-data).
 *
 * The source package also contains thousands of unions and wards. Shipping all
 * of that to every checkout browser would waste bandwidth, so this script keeps
 * only District -> City/Town -> Thana/Area and commits the deterministic result.
 * Run `pnpm data:generate` after updating the source package.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dataRoot = join(root, 'node_modules/bangladesh-geo-data/dist/data/data')

const read = (name) => JSON.parse(readFileSync(join(dataRoot, `${name}.json`), 'utf8'))

const districts = read('districts')
const upazilas = read('upazilas')
const cityCorporations = read('city_corporations')
const thanas = read('thanas')

// Preserve the storefront/shipping spellings already used in the database.
const DISTRICT_NAMES = {
  Bogra: 'Bogura',
  'Chapai Nawabganj': 'Chapainawabganj',
  Jessore: 'Jashore',
  Jhalokathi: 'Jhalokati',
}

// Source v4.0.9 links Ashulia to Dhamrai even though it is under Savar. Keep
// the correction explicit and tested until the upstream dataset is corrected.
const THANA_LOCALITY_OVERRIDES = {
  'Dhaka:Ashulia': 'Savar',
}

const hierarchy = {}

for (const district of [...districts].sort((a, b) => {
  const aName = DISTRICT_NAMES[a.name] ?? a.name
  const bName = DISTRICT_NAMES[b.name] ?? b.name
  return aName.localeCompare(bName)
})) {
  const districtName = DISTRICT_NAMES[district.name] ?? district.name
  const localities = []

  const districtCities = cityCorporations.filter((city) => city.districtId === district.id)
  if (districtCities.length > 0) {
    const cityIds = new Set(districtCities.map((city) => city.id))
    const areas = thanas
      .filter((thana) => cityIds.has(thana.cityCorpId))
      .map((thana) => thana.name)

    // Upstream 4.0.9 has a Cumilla City Corporation row but no thanas linked
    // to it. Its Sadar upazilas are the safest local fallback and keep the
    // dropdown usable without inventing a police-station name.
    if (areas.length === 0) {
      areas.push(
        ...upazilas
          .filter(
            (upazila) =>
              upazila.districtId === district.id && /sadar/i.test(upazila.name),
          )
          .map((upazila) => upazila.name),
      )
    }

    localities.push({ name: `${districtName} City`, areas: [...new Set(areas)].sort() })
  }

  for (const upazila of upazilas.filter((item) => item.districtId === district.id)) {
    const areas = thanas
      .filter((thana) => {
        const override = THANA_LOCALITY_OVERRIDES[`${districtName}:${thana.name}`]
        return override ? override === upazila.name : thana.upazilaId === upazila.id
      })
      .map((thana) => thana.name)

    // Every selectable locality must have a selectable delivery area, even if
    // the source has no separate police-station row for it.
    areas.push(upazila.name)
    localities.push({ name: upazila.name, areas: [...new Set(areas)].sort() })
  }

  hierarchy[districtName] = localities.sort((a, b) => a.name.localeCompare(b.name))
}

if (Object.keys(hierarchy).length !== 64) {
  throw new Error(`Expected 64 districts, received ${Object.keys(hierarchy).length}`)
}

const output = `/**
 * Generated by scripts/generate-bd-locations.mjs from bangladesh-geo-data 4.0.9
 * (MIT, https://www.npmjs.com/package/bangladesh-geo-data).
 * Do not edit by hand; update the generator or its documented overrides.
 */
export const BD_LOCATION_HIERARCHY = ${JSON.stringify(hierarchy, null, 2)} as const
`

writeFileSync(join(root, 'src/lib/bd-locations.generated.ts'), output)
